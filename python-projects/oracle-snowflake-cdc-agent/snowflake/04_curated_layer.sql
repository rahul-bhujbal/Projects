-- ======================= T001 =======================
CREATE TABLE IF NOT EXISTS SAP_CURATED.SD.T001 (
  "MANDT" VARCHAR(3) NOT NULL,
  "BUKRS" VARCHAR(4) NOT NULL,
  "BUTXT" VARCHAR(25),
  "ORT01" VARCHAR(25),
  "LAND1" VARCHAR(3),
  "WAERS" VARCHAR(5),
  "SPRAS" VARCHAR(1),
  "KTOPL" VARCHAR(4),
  CDC_OP          VARCHAR(1),
  CDC_SCN         NUMBER(38,0),
  CDC_SOURCE_TS   TIMESTAMP_NTZ,
  CDC_LOADED_AT   TIMESTAMP_LTZ,
  CDC_IS_DELETED  BOOLEAN,
  CONSTRAINT PK_CUR_T001 PRIMARY KEY ("MANDT", "BUKRS")
);

CREATE STREAM IF NOT EXISTS SAP_CURATED.SD.STM_T001
  ON TABLE SAP_RAW.SD.T001_RAW
  APPEND_ONLY = TRUE
  SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE TASK SAP_CURATED.SD.TSK_T001
  WAREHOUSE = SAP_TRANSFORM_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('SAP_CURATED.SD.STM_T001')
AS
MERGE INTO SAP_CURATED.SD.T001 t
USING (
    SELECT
      R:"MANDT"::VARCHAR AS "MANDT",
      R:"BUKRS"::VARCHAR AS "BUKRS",
      R:"BUTXT"::VARCHAR AS "BUTXT",
      R:"ORT01"::VARCHAR AS "ORT01",
      R:"LAND1"::VARCHAR AS "LAND1",
      R:"WAERS"::VARCHAR AS "WAERS",
      R:"SPRAS"::VARCHAR AS "SPRAS",
      R:"KTOPL"::VARCHAR AS "KTOPL",
      CDC_OP, CDC_SCN, CDC_SOURCE_TS
    FROM (
      SELECT COALESCE(RECORD_CONTENT:after, RECORD_CONTENT:before)          AS R,
             RECORD_CONTENT:op::VARCHAR                                     AS CDC_OP,
             TRY_TO_NUMBER(RECORD_CONTENT:source.scn::VARCHAR)              AS CDC_SCN,
             TO_TIMESTAMP_NTZ(RECORD_CONTENT:source.ts_ms::NUMBER, 3)       AS CDC_SOURCE_TS,
             RECORD_METADATA:offset::NUMBER                                 AS KAFKA_OFFSET
      FROM SAP_CURATED.SD.STM_T001
      WHERE RECORD_CONTENT:op IS NOT NULL
    )
    QUALIFY ROW_NUMBER() OVER (PARTITION BY R:"MANDT"::VARCHAR, R:"BUKRS"::VARCHAR
                               ORDER BY CDC_SCN DESC, KAFKA_OFFSET DESC) = 1
) s
ON t."MANDT" = s."MANDT" AND t."BUKRS" = s."BUKRS"
WHEN MATCHED AND s.CDC_SCN >= t.CDC_SCN THEN UPDATE SET
  "BUTXT" = s."BUTXT",
  "ORT01" = s."ORT01",
  "LAND1" = s."LAND1",
  "WAERS" = s."WAERS",
  "SPRAS" = s."SPRAS",
  "KTOPL" = s."KTOPL",
  CDC_OP = s.CDC_OP,
  CDC_SCN = s.CDC_SCN,
  CDC_SOURCE_TS = s.CDC_SOURCE_TS,
  CDC_LOADED_AT = CURRENT_TIMESTAMP(),
  CDC_IS_DELETED = (s.CDC_OP = 'd')
WHEN NOT MATCHED THEN INSERT ("MANDT", "BUKRS", "BUTXT", "ORT01", "LAND1", "WAERS", "SPRAS", "KTOPL", CDC_OP, CDC_SCN, CDC_SOURCE_TS, CDC_LOADED_AT, CDC_IS_DELETED)
  VALUES (s."MANDT", s."BUKRS", s."BUTXT", s."ORT01", s."LAND1", s."WAERS", s."SPRAS", s."KTOPL", s.CDC_OP, s.CDC_SCN, s.CDC_SOURCE_TS, CURRENT_TIMESTAMP(), (s.CDC_OP = 'd'));

