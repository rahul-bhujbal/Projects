/* ---------------------------------------------------------------------
   C. Business view: net revenue per day.
      Cancellations (S1, VBTYP N) and credit memos (VBTYP O) are
      subtracted, so a cancelled-and-rebilled invoice counts once.
   --------------------------------------------------------------------- */
CREATE OR REPLACE VIEW SAP_CORE.SD.V_NET_REVENUE_DAILY AS
SELECT
  "FKDAT"                                                    AS BILLING_DATE,
  SUM(CASE WHEN "VBTYP" = 'M'          THEN "NETWR"
           WHEN "VBTYP" IN ('N', 'O')  THEN -"NETWR" END)     AS NET_REVENUE_INR,
  COUNT_IF("VBTYP" = 'M')                                    AS INVOICES,
  COUNT_IF("VBTYP" = 'N')                                    AS CANCELLATIONS,
  COUNT_IF("VBTYP" = 'O')                                    AS CREDIT_MEMOS
FROM SAP_CORE.SD.V_VBRK
GROUP BY "FKDAT";

