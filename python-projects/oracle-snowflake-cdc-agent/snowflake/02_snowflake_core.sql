-- ======================= T001 =======================
CREATE TABLE IF NOT EXISTS SAP_CORE.SD.T001 (
  "MANDT" STRING NOT NULL,
  "BUKRS" STRING NOT NULL,
  ROW_DATA   VARIANT,
  OP         STRING,
  LAST_SCN   NUMBER(38,0),
  IS_DELETED BOOLEAN,
  SOURCE_TS  TIMESTAMP_NTZ,
  LOADED_AT  TIMESTAMP_LTZ,
  CONSTRAINT PK_T001 PRIMARY KEY ("MANDT", "BUKRS")
);

CREATE STREAM IF NOT EXISTS SAP_CORE.SD.STM_T001_RAW
  ON TABLE SAP_RAW.SD.T001_RAW
  APPEND_ONLY = TRUE
  SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE TASK SAP_CORE.SD.TSK_T001
  WAREHOUSE = SAP_TRANSFORM_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('SAP_CORE.SD.STM_T001_RAW')
AS
MERGE INTO SAP_CORE.SD.T001 t
USING (
    SELECT
      COALESCE(RECORD_CONTENT:after, RECORD_CONTENT:before)        AS ROW_DATA,
      RECORD_CONTENT:op::STRING                                     AS OP,
      RECORD_CONTENT:source.scn::NUMBER(38,0)                       AS SCN,
      TO_TIMESTAMP_NTZ(RECORD_CONTENT:source.ts_ms::NUMBER, 3)      AS SOURCE_TS,
      RECORD_METADATA:offset::NUMBER                                AS KAFKA_OFFSET,
      ROW_DATA:"MANDT"::STRING AS "MANDT",
      ROW_DATA:"BUKRS"::STRING AS "BUKRS"
    FROM SAP_CORE.SD.STM_T001_RAW
    WHERE RECORD_CONTENT:op IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY "MANDT", "BUKRS"
                               ORDER BY SCN DESC, KAFKA_OFFSET DESC) = 1
) s
ON t."MANDT" = s."MANDT" AND t."BUKRS" = s."BUKRS"
WHEN MATCHED AND s.SCN >= t.LAST_SCN THEN UPDATE SET
  ROW_DATA   = s.ROW_DATA,
  OP         = s.OP,
  LAST_SCN   = s.SCN,
  IS_DELETED = (s.OP = 'd'),
  SOURCE_TS  = s.SOURCE_TS,
  LOADED_AT  = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT ("MANDT", "BUKRS", ROW_DATA, OP, LAST_SCN, IS_DELETED, SOURCE_TS, LOADED_AT)
  VALUES (s."MANDT", s."BUKRS", s.ROW_DATA, s.OP, s.SCN, s.OP = 'd', s.SOURCE_TS, CURRENT_TIMESTAMP());

CREATE OR REPLACE VIEW SAP_CORE.SD.V_T001 AS
SELECT
  ROW_DATA:"MANDT"::STRING AS "MANDT",
  ROW_DATA:"BUKRS"::STRING AS "BUKRS",
  ROW_DATA:"BUTXT"::STRING AS "BUTXT",
  ROW_DATA:"ORT01"::STRING AS "ORT01",
  ROW_DATA:"LAND1"::STRING AS "LAND1",
  ROW_DATA:"WAERS"::STRING AS "WAERS",
  ROW_DATA:"SPRAS"::STRING AS "SPRAS",
  ROW_DATA:"KTOPL"::STRING AS "KTOPL",
  OP        AS CDC_OP,
  LAST_SCN  AS CDC_SCN,
  SOURCE_TS AS CDC_SOURCE_TS,
  LOADED_AT AS CDC_LOADED_AT
FROM SAP_CORE.SD.T001
WHERE NOT IS_DELETED;

