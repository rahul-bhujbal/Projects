"""
Reads oracle/s4_sd_oracle_ddl.sql (tables, columns, types, primary keys) and
generates everything that must list the 30 SAP tables, so they stay in sync:

  connectors/snowflake-sink.json   Snowflake Kafka connector v4 config (topic -> <TABLE>_RAW)
  snowflake/02_snowflake_core.sql  streams + MERGE tasks + typed views in SAP_CORE.SD
  snowflake/03_checks.sql          row counts, exactly-once, latency, task history
  oracle/91_row_counts.sql         row counts in Oracle, to compare with Snowflake

Run after changing the Oracle DDL:  python3 scripts/generate_from_ddl.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DDL = ROOT / "oracle" / "s4_sd_oracle_ddl.sql"

TOPIC_PREFIX = "sap"            # Debezium topic.prefix
ORACLE_SCHEMA = "SAPSD"
RAW = "SAP_RAW.SD"
CORE = "SAP_CORE.SD"
WAREHOUSE = "SAP_TRANSFORM_WH"
TASK_SCHEDULE = "1 MINUTE"


# ---------------------------------------------------------------------------
# Parse the Oracle DDL
# ---------------------------------------------------------------------------
def parse_ddl(text):
    tables = []
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", text, re.S | re.I):
        name, body = m.group(1).upper(), m.group(2)
        cols, pk = [], None
        for raw_line in body.split("\n"):
            line = raw_line.split("--")[0].strip().rstrip(",")
            if not line:
                continue
            pk_m = re.match(r"CONSTRAINT \w+ PRIMARY KEY \(([^)]*)\)", line, re.I)
            if pk_m:
                pk = [c.strip().upper() for c in pk_m.group(1).split(",")]
                continue
            col_m = re.match(r"(\w+)\s+(VARCHAR2|NUMBER|DATE|RAW)(?:\((\d+)(?:\s*,\s*(\d+))?\))?", line, re.I)
            if col_m:
                cols.append((col_m.group(1).upper(), col_m.group(2).upper(),
                             col_m.group(3), col_m.group(4)))
        if not pk:
            raise SystemExit(f"No primary key found for {name}")
        tables.append({"name": name, "cols": cols, "pk": pk})
    return tables


def typed(col, typ, p, s, src="ROW_DATA"):
    """Snowflake expression converting a Debezium JSON field to a typed column."""
    ref = f'{src}:"{col}"'
    if typ in ("VARCHAR2", "RAW"):            # RAW arrives base64-encoded
        return f"{ref}::STRING"
    if typ == "NUMBER":                       # decimal.handling.mode=string -> cast
        return f"{ref}::NUMBER({p},{s or 0})" if p else f"{ref}::NUMBER"
    if typ == "DATE":                         # Oracle DATE -> epoch milliseconds
        return f"TO_DATE(TO_TIMESTAMP_NTZ({ref}::NUMBER, 3))"
    raise ValueError(typ)


def q(name):
    return f'"{name}"'


# ---------------------------------------------------------------------------
# Snowflake sink connector config
# ---------------------------------------------------------------------------
def sink_config(tables):
    topic_map = ",".join(f"{TOPIC_PREFIX}.{ORACLE_SCHEMA}.{t['name']}:{t['name']}_RAW" for t in tables)
    return {
        "connector.class": "com.snowflake.kafka.connector.SnowflakeStreamingSinkConnector",
        "tasks.max": "3",
        "topics.regex": f"{TOPIC_PREFIX}\\.{ORACLE_SCHEMA}\\..*",
        "snowflake.topic2table.map": topic_map,

        "snowflake.url.name": "__SNOWFLAKE_URL__",
        "snowflake.user.name": "KAFKA_CONNECTOR_USER",
        "snowflake.private.key": "${file:/opt/secrets/snowflake.properties:private.key}",
        "snowflake.role.name": "KAFKA_CONNECTOR_ROLE",
        "snowflake.database.name": RAW.split(".")[0],
        "snowflake.schema.name": RAW.split(".")[1],

        "snowflake.enable.schematization": "false",
        "snowflake.autocreate.table.type": "snowflake",
        "snowflake.validation": "server_side",
        "snowflake.streaming.validate.compatibility.with.classic": "false",
        "errors.tolerance": "none",
        "errors.log.enable": "true",

        "key.converter": "org.apache.kafka.connect.storage.StringConverter",
        "value.converter": "org.apache.kafka.connect.json.JsonConverter",
        "value.converter.schemas.enable": "false",
    }


# ---------------------------------------------------------------------------
# Snowflake current-state layer
# ---------------------------------------------------------------------------
def core_sql(tables):
    out = [f"""/* =====================================================================
   SAP_CORE.SD: current state of every SAP SD table, built from the raw
   CDC events the Kafka connector lands in {RAW}.<TABLE>_RAW.
   GENERATED by scripts/generate_from_ddl.py - edit the generator, not this file.

   Per table:
     {CORE}.<TABLE>          one row per primary key: full row as VARIANT,
                                 CDC op, last SCN, soft-delete flag
     {CORE}.STM_<TABLE>_RAW  append-only stream on the raw table
     {CORE}.TSK_<TABLE>      task: every {TASK_SCHEDULE.lower()}, MERGE new events (only if any)
     {CORE}.V_<TABLE>        typed view of live (non-deleted) rows

   Rules enforced by the MERGE:
     - latest event per key wins (Oracle SCN, then Kafka offset)
     - an event older than what is stored is ignored  (no double counting,
       safe to replay)
     - deletes become IS_DELETED = TRUE (recoverable, auditable)

   Run AFTER the Kafka connector has created the raw tables
   (SHOW TABLES IN SCHEMA {RAW}; should list 30 *_RAW tables).
   ===================================================================== */

/* ---------------------------------------------------------------------
   A. Change tracking on the raw tables (needed for streams).
      The connector's role owns them; SYSADMIN inherits that role.
   --------------------------------------------------------------------- */
USE ROLE SYSADMIN;
"""]
    for t in tables:
        out.append(f"ALTER TABLE IF EXISTS {RAW}.{t['name']}_RAW SET CHANGE_TRACKING = TRUE;")

    out.append(f"""
/* ---------------------------------------------------------------------
   B. Core tables, streams, merge tasks, typed views
      Requires: GRANT ROLE SAP_TRANSFORM_ROLE TO USER <you>;
   --------------------------------------------------------------------- */
USE ROLE SAP_TRANSFORM_ROLE;
USE WAREHOUSE {WAREHOUSE};
""")

    for t in tables:
        name, pk, cols = t["name"], t["pk"], t["cols"]
        pk_q = [q(c) for c in pk]
        pk_def = ",\n  ".join(f"{q(c)} STRING NOT NULL" for c in pk)
        key_extract = ",\n      ".join(f'ROW_DATA:"{c}"::STRING AS {q(c)}' for c in pk)
        on_clause = " AND ".join(f"t.{c} = s.{c}" for c in pk_q)
        insert_cols = ", ".join(pk_q + ["ROW_DATA", "OP", "LAST_SCN", "IS_DELETED", "SOURCE_TS", "LOADED_AT"])
        insert_vals = ", ".join([f"s.{c}" for c in pk_q] +
                                ["s.ROW_DATA", "s.OP", "s.SCN", "s.OP = 'd'", "s.SOURCE_TS", "CURRENT_TIMESTAMP()"])
        view_cols = ",\n  ".join(f"{typed(c, ty, p, s)} AS {q(c)}" for c, ty, p, s in cols)

        out.append(f"""
-- ======================= {name} =======================
CREATE TABLE IF NOT EXISTS {CORE}.{name} (
  {pk_def},
  ROW_DATA   VARIANT,
  OP         STRING,
  LAST_SCN   NUMBER(38,0),
  IS_DELETED BOOLEAN,
  SOURCE_TS  TIMESTAMP_NTZ,
  LOADED_AT  TIMESTAMP_LTZ,
  CONSTRAINT PK_{name} PRIMARY KEY ({", ".join(pk_q)})
);

CREATE STREAM IF NOT EXISTS {CORE}.STM_{name}_RAW
  ON TABLE {RAW}.{name}_RAW
  APPEND_ONLY = TRUE
  SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE TASK {CORE}.TSK_{name}
  WAREHOUSE = {WAREHOUSE}
  SCHEDULE = '{TASK_SCHEDULE}'
  WHEN SYSTEM$STREAM_HAS_DATA('{CORE}.STM_{name}_RAW')
AS
MERGE INTO {CORE}.{name} t
USING (
    SELECT
      COALESCE(RECORD_CONTENT:after, RECORD_CONTENT:before)        AS ROW_DATA,
      RECORD_CONTENT:op::STRING                                     AS OP,
      RECORD_CONTENT:source.scn::NUMBER(38,0)                       AS SCN,
      TO_TIMESTAMP_NTZ(RECORD_CONTENT:source.ts_ms::NUMBER, 3)      AS SOURCE_TS,
      RECORD_METADATA:offset::NUMBER                                AS KAFKA_OFFSET,
      {key_extract}
    FROM {CORE}.STM_{name}_RAW
    WHERE RECORD_CONTENT:op IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY {", ".join(pk_q)}
                               ORDER BY SCN DESC, KAFKA_OFFSET DESC) = 1
) s
ON {on_clause}
WHEN MATCHED AND s.SCN >= t.LAST_SCN THEN UPDATE SET
  ROW_DATA   = s.ROW_DATA,
  OP         = s.OP,
  LAST_SCN   = s.SCN,
  IS_DELETED = (s.OP = 'd'),
  SOURCE_TS  = s.SOURCE_TS,
  LOADED_AT  = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT ({insert_cols})
  VALUES ({insert_vals});

CREATE OR REPLACE VIEW {CORE}.V_{name} AS
SELECT
  {view_cols},
  OP        AS CDC_OP,
  LAST_SCN  AS CDC_SCN,
  SOURCE_TS AS CDC_SOURCE_TS,
  LOADED_AT AS CDC_LOADED_AT
FROM {CORE}.{name}
WHERE NOT IS_DELETED;""")

    out.append(f"""
/* ---------------------------------------------------------------------
   C. Business view: net revenue per day.
      Cancellations (S1, VBTYP N) and credit memos (VBTYP O) are
      subtracted, so a cancelled-and-rebilled invoice counts once.
   --------------------------------------------------------------------- */
CREATE OR REPLACE VIEW {CORE}.V_NET_REVENUE_DAILY AS
SELECT
  "FKDAT"                                                    AS BILLING_DATE,
  SUM(CASE WHEN "VBTYP" = 'M'          THEN "NETWR"
           WHEN "VBTYP" IN ('N', 'O')  THEN -"NETWR" END)     AS NET_REVENUE_INR,
  COUNT_IF("VBTYP" = 'M')                                    AS INVOICES,
  COUNT_IF("VBTYP" = 'N')                                    AS CANCELLATIONS,
  COUNT_IF("VBTYP" = 'O')                                    AS CREDIT_MEMOS
FROM {CORE}.V_VBRK
GROUP BY "FKDAT";

/* ---------------------------------------------------------------------
   D. Start the tasks, and run each once now for the initial snapshot
   --------------------------------------------------------------------- */""")
    for t in tables:
        out.append(f"ALTER TASK {CORE}.TSK_{t['name']} RESUME;")
    out.append("")
    for t in tables:
        out.append(f"EXECUTE TASK {CORE}.TSK_{t['name']};")

    out.append(f"""
/* ---------------------------------------------------------------------
   E. Pause everything (saves trial credits). Streams keep their position
      while paused, but go stale if left longer than the table's data
      retention plus MAX_DATA_EXTENSION_TIME_IN_DAYS (default 14 days).
   --------------------------------------------------------------------- */""")
    for t in tables:
        out.append(f"-- ALTER TASK {CORE}.TSK_{t['name']} SUSPEND;")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------
def checks_sql(tables):
    raw_counts = "\nUNION ALL ".join(
        f"SELECT '{t['name']}' AS table_name, COUNT(*) AS raw_events, "
        f"COUNT(DISTINCT RECORD_METADATA:partition, RECORD_METADATA:offset) AS distinct_events "
        f"FROM {RAW}.{t['name']}_RAW" for t in tables)
    core_counts = "\nUNION ALL ".join(
        f"SELECT '{t['name']}' AS TABLE_NAME, COUNT_IF(NOT IS_DELETED) AS LIVE_ROWS, "
        f"COUNT_IF(IS_DELETED) AS DELETED_ROWS FROM {CORE}.{t['name']}"
        for t in tables)
    lat_union = "\n  UNION ALL ".join(
        f"SELECT RECORD_CONTENT, RECORD_METADATA FROM {RAW}.{t['name']}_RAW" for t in tables)
    return f"""/* =====================================================================
   Pipeline checks. GENERATED by scripts/generate_from_ddl.py
   ===================================================================== */
USE ROLE SAP_TRANSFORM_ROLE;
USE WAREHOUSE {WAREHOUSE};

-- 1. Exactly-once: raw_events must equal distinct_events for every table,
--    even after you kill and restart the Kafka Connect container mid-load.
{raw_counts}
ORDER BY 1;

-- 2. Current-state row counts. LIVE_ROWS must match oracle/91_row_counts.sql.
{core_counts}
ORDER BY 1;

-- 3. Latency of streamed changes (snapshot rows excluded), last hour:
--    Oracle commit -> Snowflake connector push.
SELECT
  COUNT(*)                                                            AS changes,
  APPROX_PERCENTILE((RECORD_METADATA:SnowflakeConnectorPushTime::NUMBER
                     - RECORD_CONTENT:source.ts_ms::NUMBER) / 1000, 0.5) AS p50_seconds,
  APPROX_PERCENTILE((RECORD_METADATA:SnowflakeConnectorPushTime::NUMBER
                     - RECORD_CONTENT:source.ts_ms::NUMBER) / 1000, 0.9) AS p90_seconds
FROM (
  {lat_union}
)
WHERE RECORD_CONTENT:op::STRING IN ('c', 'u', 'd')
  AND RECORD_CONTENT:source.ts_ms::NUMBER
      > DATE_PART(epoch_millisecond, DATEADD(hour, -1, CURRENT_TIMESTAMP()));

-- 4. Recent MERGE task runs (look for FAILED and its ERROR_MESSAGE).
SELECT name, state, scheduled_time, completed_time, error_message
FROM TABLE(SAP_CORE.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => DATEADD(hour, -1, CURRENT_TIMESTAMP()),
       RESULT_LIMIT => 200))
ORDER BY scheduled_time DESC;

-- 5. Net revenue: compare with the Oracle query at the end of
--    oracle/s4_sd_sample_data.sql.
SELECT SUM(NET_REVENUE_INR) AS net_revenue_inr FROM {CORE}.V_NET_REVENUE_DAILY;

-- 6. Follow one order through the pipeline (the cancelled-and-rebilled one).
SELECT "VBELN", "AUART", "NETWR", "GBSTK", CDC_OP, CDC_SCN, CDC_SOURCE_TS, CDC_LOADED_AT
FROM {CORE}.V_VBAK
WHERE "VBELN" = '0000010006';
"""


def oracle_counts_sql(tables):
    body = "\nUNION ALL ".join(f"SELECT '{t['name']}', COUNT(*) FROM {t['name'].lower()}" for t in tables)
    return f"""-- Row counts per SAP SD table in Oracle. GENERATED by scripts/generate_from_ddl.py
-- Compare with check 2 in snowflake/03_checks.sql.
SET PAGESIZE 100 FEEDBACK OFF
COLUMN table_name FORMAT A16
SELECT * FROM (
{body}
) ORDER BY 1;
EXIT
"""


def main():
    tables = parse_ddl(DDL.read_text())
    if len(tables) != 30:
        raise SystemExit(f"Expected 30 tables, parsed {len(tables)}")
    (ROOT / "connectors" / "snowflake-sink.json").write_text(json.dumps(sink_config(tables), indent=2) + "\n")
    (ROOT / "snowflake" / "02_snowflake_core.sql").write_text(core_sql(tables))
    (ROOT / "snowflake" / "03_checks.sql").write_text(checks_sql(tables))
    (ROOT / "oracle" / "91_row_counts.sql").write_text(oracle_counts_sql(tables))
    print(f"Generated files for {len(tables)} tables:", ", ".join(t["name"] for t in tables))


if __name__ == "__main__":
    main()
